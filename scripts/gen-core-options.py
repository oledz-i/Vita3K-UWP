"""Writes src/Vita3K.UWP/CoreOptions.h from scripts/core-options.json.

core-options.json is a dump of option_defs_us in the pinned core's
libretro_core_options.h. The frontend shows the options that mean something
on Xbox; the rest keep the core's defaults.
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((root / 'scripts/core-options.json').read_text(encoding='utf-8'))
cats = {c[0]: c[1] for c in data['cats']}

# Shown, in this order. Anything else keeps the core default.
shown = [
    'vita3k_resolution_multiplier', 'vita3k_screen_filter', 'vita3k_anisotropic_filtering',
    'vita3k_v_sync', 'vita3k_async_pipeline', 'vita3k_compile_overlay', 'vita3k_surface_sync',
    'vita3k_memory_mapping', 'vita3k_high_accuracy',
    'vita3k_cpu_opt',
    'vita3k_pkg_mode',
    'vita3k_sys_lang', 'vita3k_sys_button', 'vita3k_sys_date_format', 'vita3k_sys_time_format',
    'vita3k_pstv_mode', 'vita3k_modules_mode', 'vita3k_fps_hack', 'vita3k_file_loading_delay',
    'vita3k_audio_volume', 'vita3k_ngs_enable',
    'vita3k_psn_signed_in', 'vita3k_http_enable',
]
xbox_notes = {
    'vita3k_resolution_multiplier': 'Series S: stay at 1x until games run well. Series X can try 2x.',
    'vita3k_memory_mapping': 'On Xbox the Vulkan layer may not support the higher methods. Keep Double Buffer unless testing.',
    'vita3k_cpu_opt': 'Off is far slower and only useful to tell a JIT problem from a game problem.',
    'vita3k_pkg_mode': 'Run without installing needs sparse-file support; the core falls back to installing when it is missing.',
}
category_names = {'install': 'Content'}


def cstr(s):
    return 'L"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', ' ') + '"'


def label_of(value, label):
    if label:
        return label
    return {'enabled': 'On', 'disabled': 'Off'}.get(value, value)


by_key = {o['key']: o for o in data['opts']}
rows = []
for key in shown:
    o = by_key[key]
    info = (o['info'] or '').strip()
    if key in xbox_notes:
        info = (info + ' ' + xbox_notes[key]).strip()
    values = ', '.join('{ "%s", %s }' % (v[0], cstr(label_of(v[0], v[1]))) for v in o['values'])
    category = category_names.get(o['cat'], cats.get(o['cat'], o['cat']))
    rows.append('    { "%s", %s, %s, %s, "%s", %d, { %s } },' % (
        key, cstr(category), cstr(o['desc']), cstr(info), o['def'], len(o['values']), values))
max_values = max(len(by_key[k]['values']) for k in shown)
out = f'''// Generated by scripts/gen-core-options.py from the pinned core's options. Do not edit.
#pragma once
#include <cstddef>

namespace vita3k_uwp {{
struct CoreOptionValue {{
    const char* value;
    const wchar_t* label;
}};
struct CoreOptionDef {{
    const char* key;
    const wchar_t* category;
    const wchar_t* label;
    const wchar_t* info;
    const char* defaultValue;
    std::size_t valueCount;
    CoreOptionValue values[{max_values}];
}};
inline const CoreOptionDef kCoreOptions[] = {{
{chr(10).join(rows)}
}};
constexpr std::size_t kCoreOptionCount = sizeof(kCoreOptions) / sizeof(kCoreOptions[0]);
}} // namespace vita3k_uwp
'''
(root / 'src/Vita3K.UWP/CoreOptions.h').write_text(out, encoding='utf-8')
print(f'{len(rows)} options written')
